HEADER = """
from opentrons import protocol_api
requirements = {"robotType": "OT-2", "apiLevel": "2.20"}
def run(protocol):
    tips_300 = protocol.load_labware("opentrons_96_tiprack_300ul", 1)
    tips_20 = protocol.load_labware("opentrons_96_tiprack_20ul", 4)
    plate = protocol.load_labware("corning_96_wellplate_360ul_flat", 2)
    reservoir = protocol.load_labware("nest_12_reservoir_15ml", 3)
    small = protocol.load_instrument("p20_single_gen2", "left", tip_racks=[tips_20])
    large = protocol.load_instrument("p300_single_gen2", "right", tip_racks=[tips_300])
"""


def test_good_design_compiles_and_simulates(assay, workcell, good_design, tmp_path):
    result = check(good_design, assay, workcell, out_dir=tmp_path)
    assert result.ok, result.errors
    assert result.sim.ok
    assert len(result.sim.steps) > 100
    assert result.sim.tips_used == {"large": 4, "small": 38}
    assert (tmp_path / "protocol.py").exists()


def test_ledger_equals_plan(assay, workcell, good_design, tmp_path):
    result = check(good_design, assay, workcell, out_dir=tmp_path)
    got = {(e.dest_well, e.reagent): e.volume_ul for e in result.sim.ledger}
    want = {(w.well, r): v for w in result.plan.wells for r, v in w.add_ul.items() if v > 0}
    assert got == want


def test_generated_protocol_simulates_on_its_own_as_a_file(assay, workcell, good_design, tmp_path):
    result = check(good_design, assay, workcell, out_dir=tmp_path)
    env = dict(os.environ)
    proc = subprocess.run(
        [sys.executable, "-m", "opentrons.simulate", str(tmp_path / "protocol.py")],
        capture_output=True,
        text=True,
        env=env,
        timeout=300,
    )
    assert proc.returncode == 0, proc.stderr[-2000:]
    assert "Dispensing" in proc.stdout
    assert result.ok


def test_protocol_header_matches_spec(assay, workcell, good_design, tmp_path):
    check(good_design, assay, workcell, out_dir=tmp_path)
    text = (tmp_path / "protocol.py").read_text()
    assert text.startswith("# Generated by labauto from plan p-example-good-factorial")
    assert 'requirements = {"robotType": "OT-2", "apiLevel": "2.20"}' in text
    assert "apiLevel" not in text.split("requirements")[0]
    assert text.count(".aspirate(") == text.count(".dispense(")


def test_run_log_strings_are_stable():
    """The ledger depends on these text prefixes. A library change that moves them fails here."""
    src = HEADER + (
        "    small.pick_up_tip()\n"
        "    small.aspirate(5, reservoir['A1'])\n"
        "    small.dispense(5, plate['E1'])\n"
        "    small.drop_tip()\n"
    )
    sim = simulate_source(src, None)
    assert sim.ok
    starts = [s.split(" ")[0] for s in sim.steps]
    assert starts[:3] == ["Picking", "Aspirating", "Dispensing"]


