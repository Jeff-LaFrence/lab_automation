"""The OT-2 backend: compile, simulate, ledger, error mapping, and the simulator's blind spots."""

from __future__ import annotations

import os
import subprocess
import sys

import pytest
from conftest import make_design

from labauto.instruments.opentrons_ot2 import OpentronsOT2, simulate_source
from labauto.models import Plan, PlanWell
from labauto.pipeline import check

HEADER = """
from opentrons import protocol_api
requirements = {"robotType": "OT-2", "apiLevel": "2.20"}
def run(protocol):
    tips_300 = protocol.load_labware("opentrons_96_tiprack_300ul", 1)
    tips_20 = protocol.load_labware("opentrons_96_tiprack_20ul", 4)
    plate = protocol.load_labware("corning_96_wellplate_360ul_flat", 2)
    reservoir = protocol.load_labware("nest_12_reservoir_15ml", 3)
    small = protocol.load_instrument("p20_single_gen2", "left", tip_racks=[tips_20])
    large = protocol.load_instrument("p300_single_gen2", "right", tip_racks=[tips_300])
"""


def test_good_design_compiles_and_simulates(assay, workcell, good_design, tmp_path):
    result = check(good_design, assay, workcell, out_dir=tmp_path)
    assert result.ok, result.errors
    assert result.sim.ok
    assert len(result.sim.steps) > 100
    assert result.sim.tips_used == {"large": 4, "small": 38}
    assert (tmp_path / "protocol.py").exists()


def test_ledger_equals_plan(assay, workcell, good_design, tmp_path):
    result = check(good_design, assay, workcell, out_dir=tmp_path)
    got = {(e.dest_well, e.reagent): e.volume_ul for e in result.sim.ledger}
    want = {(w.well, r): v for w in result.plan.wells for r, v in w.add_ul.items() if v > 0}
    assert got == want


def test_generated_protocol_simulates_on_its_own_as_a_file(assay, workcell, good_design, tmp_path):
    result = check(good_design, assay, workcell, out_dir=tmp_path)
    env = dict(os.environ)
    proc = subprocess.run(
        [sys.executable, "-m", "opentrons.simulate", str(tmp_path / "protocol.py")],
        capture_output=True,
        text=True,
        env=env,
        timeout=300,
    )
    assert proc.returncode == 0, proc.stderr[-2000:]
    assert "Dispensing" in proc.stdout
    assert result.ok


def test_protocol_header_matches_spec(assay, workcell, good_design, tmp_path):
    check(good_design, assay, workcell, out_dir=tmp_path)
    text = (tmp_path / "protocol.py").read_text()
    assert text.startswith("# Generated by labauto from plan p-example-good-factorial")
    assert 'requirements = {"robotType": "OT-2", "apiLevel": "2.20"}' in text
    assert "apiLevel" not in text.split("requirements")[0]
    assert text.count(".aspirate(") == text.count(".dispense(")


def test_run_log_strings_are_stable():
    """The ledger depends on these text prefixes. A library change that moves them fails here."""
    src = HEADER + (
        "    small.pick_up_tip()\n"
        "    small.aspirate(5, reservoir['A1'])\n"
        "    small.dispense(5, plate['E1'])\n"
        "    small.drop_tip()\n"
    )
    sim = simulate_source(src, None)
    assert sim.ok
    starts = [s.split(" ")[0] for s in sim.steps]
    assert starts[:3] == ["Picking", "Aspirating", "Dispensing"]


# ---------------------------------------------------------------- simulator layer alone


def test_simulator_catches_deck_conflict_when_rules_are_skipped(
    assay, workcell, good_design, tmp_path
):
    data = workcell.model_dump(mode="json")
    data["deck"][3]["position"] = {"slot": 2}
    conflict = type(workcell).model_validate(data)
    result = check(good_design, assay, conflict, out_dir=tmp_path, skip_layers={"workcell"})
    assert result.failed_layer == "simulator"
    assert result.errors[0].code == "SIM_DECK_CONFLICT"
    assert "LocationIsOccupiedError" in result.errors[0].message
    assert "/home/" not in result.errors[0].message


def test_simulator_catches_tip_shortfall_when_rules_are_skipped(assay, workcell, tmp_path):
    design = make_design(
        grid={
            "catalyst_mol_pct": [1, 2, 3, 4, 5, 6, 7, 8, 9],
            "base_equiv": [0.5, 0.75],
            "cosolvent_pct": [20],
        },
        replicates=5,
    )
    result = check(design, assay, workcell, out_dir=tmp_path, skip_layers={"workcell"})
    assert result.failed_layer == "simulator"
    assert result.errors[0].code == "SIM_OUT_OF_TIPS"


def test_simulator_error_mapping_for_bad_volume_and_unknown_labware():
    over = HEADER + "    small.pick_up_tip()\n    small.aspirate(25, reservoir['A1'])\n"
    assert simulate_source(over, None).error.code == "SIM_BAD_VOLUME"
    missing = HEADER.replace("nest_12_reservoir_15ml", "nest_12_reservoir_99ml")
    assert simulate_source(missing, None).error.code == "SIM_LABWARE_NOT_FOUND"
    no_tip = HEADER + "    small.aspirate(5, reservoir['A1'])\n"
    assert simulate_source(no_tip, None).error.code == "SIM_OTHER"


# ---------------------------------------------------------------- blind spots, pinned on purpose


def test_simulator_accepts_overfill():
    """600 uL into a 360 uL well passes the vendor simulator. The plan rules exist for this."""
    src = HEADER + (
        "    large.pick_up_tip()\n"
        + "".join(
            "    large.aspirate(200, reservoir['A1'])\n    large.dispense(200, plate['E1'])\n"
            for _ in range(3)
        )
        + "    large.drop_tip()\n"
    )
    assert simulate_source(src, None).ok


def test_simulator_accepts_overfill_through_the_pipeline(assay, workcell, tmp_path):
    plan = Plan(
        plan_id="p-overfill",
        assay_id=assay.assay_id,
        wells=[
            PlanWell(
                well="E1",
                role="sample",
                add_ul={"solvent": 280, "substrate": 280, "cosolvent": 40},
            )
        ],
        totals_ul={"solvent": 280, "substrate": 280, "cosolvent": 40},
    )
    result = check(plan, assay, workcell, out_dir=tmp_path, skip_layers={"plan"})
    assert result.ok


def test_simulator_accepts_below_minimum_volume():
    """A 5 uL aspirate on the 20 to 300 uL pipette passes. The workcell rules exist for this."""
    src = HEADER + (
        "    large.pick_up_tip()\n"
        "    large.aspirate(5, reservoir['A1'])\n"
        "    large.dispense(5, plate['E1'])\n"
        "    large.drop_tip()\n"
    )
    assert simulate_source(src, None).ok


def test_valid_positions():
    ot2 = OpentronsOT2()
    assert ot2.valid_position({"slot": 1})
    assert ot2.valid_position({"slot": 11})
    assert not ot2.valid_position({"slot": 12})
    assert not ot2.valid_position({"slot": "2"})
    assert not ot2.valid_position({"rails": 2})


@pytest.mark.parametrize("n", [1, 2])
def test_repeated_simulations_do_not_leak_state(assay, workcell, good_design, tmp_path, n):
    a = check(good_design, assay, workcell, out_dir=tmp_path / "a")
    b = check(good_design, assay, workcell, out_dir=tmp_path / "b")
    assert a.ok and b.ok
    assert a.sim.steps == b.sim.steps
    assert a.protocol_hash == b.protocol_hash
