def test_simulator_error_mapping_for_bad_volume_and_unknown_labware():
    over = HEADER + "    small.pick_up_tip()\n    small.aspirate(25, reservoir['A1'])\n"
    assert simulate_source(over, None).error.code == "SIM_BAD_VOLUME"
    missing = HEADER.replace("nest_12_reservoir_15ml", "nest_12_reservoir_99ml")
    assert simulate_source(missing, None).error.code == "SIM_LABWARE_NOT_FOUND"
    no_tip = HEADER + "    small.aspirate(5, reservoir['A1'])\n"
    assert simulate_source(no_tip, None).error.code == "SIM_OTHER"


