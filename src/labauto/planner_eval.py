"""Planner evaluation: run each scenario several times and publish what happened.

The table and the failure notes are built by code from the run folders. Each
failure note quotes a real error from a real attempt. Numbers are published
whatever they are.
"""

from __future__ import annotations

import statistics
import subprocess
from collections import Counter, defaultdict
from collections.abc import Callable
from datetime import datetime, timezone
from pathlib import Path

from labauto.config import DEFAULT_ASSAY, DEFAULT_WORKCELL, Settings, repo_root, resolve
from labauto.orchestrator import Clients, load_attempts, load_check, load_state, start_run

SCENARIOS = ["01_simple_factorial", "02_too_big", "03_out_of_range", "04_ambiguous", "05_reagent_limit"]
NEEDS_DEVIATION = {"02_too_big", "03_out_of_range", "05_reagent_limit"}


def git_commit() -> str:
    """The current commit, short form, or 'unknown'."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            cwd=repo_root(),
            timeout=10,
        )
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def trial_facts(run_dir: Path) -> dict:
    """What one trial did, read back from its run folder."""
    st = load_state(run_dir)
    attempts = load_attempts(run_dir)
    final = load_check(run_dir / "final") if (run_dir / "final").exists() else None
    return {
        "state": st.state,
        "first_ok": bool(attempts and attempts[0].ok),
        "local_ok": any(a.ok and a.rung == "local" for a in attempts),
        "hosted": any(a.rung == "hosted" for a in attempts),
        "person": st.state == "NEEDS_HUMAN",
        "deviations": len(final.design.deviations) if final and final.design else None,
        "seconds": sum(a.seconds for a in attempts),
        "models": {a.model for a in attempts if a.model},
        "failures": [(a.number, e) for a in attempts for e in a.errors],
    }


def evaluate(
    clients_factory: Callable[[], Clients],
    settings: Settings,
    trials: int = 5,
    runs_dir: str | Path = "runs/eval",
    out_path: Path = Path("docs/planner_eval.md"),
    scenarios: list[str] | None = None,
) -> Path:
    """Run every scenario `trials` times and write the evaluation page."""
    scenarios = scenarios or SCENARIOS
    facts: dict[str, list[dict]] = defaultdict(list)
    for scenario in scenarios:
        request = resolve(f"examples/requests/{scenario}.txt").read_text(encoding="utf-8")
        for _ in range(trials):
            run_dir = start_run(
                request, DEFAULT_ASSAY, DEFAULT_WORKCELL, clients_factory(), settings, Path(runs_dir) / scenario
            )
            facts[scenario].append(trial_facts(run_dir))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render(facts, trials), encoding="utf-8")
    return out_path


def render(facts: dict[str, list[dict]], trials: int) -> str:
    """The evaluation page as Markdown."""
    lines = [
        "# Planner evaluation",
        "",
        f"Generated by `labauto eval-planner --trials {trials}`. Every number below comes from the run folders.",
        "",
        "| Scenario | Trials | Valid first try | Valid after local repairs | Went to hosted | Handed to person | Deviations declared when needed | Median seconds |",
        "|---|---|---|---|---|---|---|---|",
    ]
    models: set[str] = set()
    failures: dict[str, list[tuple[str, int, object]]] = defaultdict(list)
    for scenario, rows in facts.items():
        n = len(rows)
        if scenario in NEEDS_DEVIATION:
            passed = [r for r in rows if r["deviations"] is not None]
            declared = sum(1 for r in passed if r["deviations"] > 0)
            dev = f"{declared} of {len(passed)} passing"
        else:
            dev = "n/a"
        median = statistics.median(r["seconds"] for r in rows) if rows else 0
        lines.append(
            f"| {scenario} | {n} | {sum(r['first_ok'] for r in rows)} | {sum(r['local_ok'] for r in rows)} "
            f"| {sum(r['hosted'] for r in rows)} | {sum(r['person'] for r in rows)} | {dev} | {median:.1f} |"
        )
        for r in rows:
            models |= r["models"]
            for number, e in r["failures"]:
                failures[e.code].append((scenario, number, e))
    lines += [
        "",
        f"Model, as reported by the endpoint: {', '.join(sorted(models)) or 'none recorded'}  ",
        f"Date: {datetime.now(timezone.utc).date().isoformat()}  ",
        "Git commit: " + git_commit(),
        "",
        "## Failure notes",
        "",
    ]
    if not failures:
        lines.append("No attempt failed a check.")
    for code, items in sorted(failures.items(), key=lambda kv: -len(kv[1])):
        scenario, number, e = items[0]
        where = Counter(s for s, _, _ in items)
        spread = ", ".join(f"{s} ({c})" for s, c in where.most_common())
        lines.append(f"- {code}: {len(items)} times, in {spread}. Example from {scenario}, attempt {number}: {e.message}")
    return "\n".join(lines) + "\n"
