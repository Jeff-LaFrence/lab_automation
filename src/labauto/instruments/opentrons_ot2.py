"""Opentrons OT-2 backend: write a Python protocol and run it in the Opentrons simulator.

The protocol uses one explicit aspirate per dispense, so the simulator's run log
lines up one to one with the worklist. The ledger is read back from that log.
"""

from __future__ import annotations

import io
import keyword
import os
import re
import time
from collections import defaultdict
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

from labauto.config import fmt_code, repo_root
from labauto.instruments.base import scrub_paths
from labauto.models import LedgerEntry, Plan, PlanError, SimResult, Workcell, Worklist

API_LEVEL = "2.20"

LABWARE_MAP = {
    "tips_300ul": "opentrons_96_tiprack_300ul",
    "tips_20ul": "opentrons_96_tiprack_20ul",
    "plate_96_flat_360ul": "corning_96_wellplate_360ul_flat",
    "reservoir_12_15ml": "nest_12_reservoir_15ml",
}
PIPETTE_MAP = {
    "p20_single": "p20_single_gen2",
    "p300_single": "p300_single_gen2",
}

# Substrings of the simulator's error text, checked in this order.
ERROR_CODES = [
    ("OutOfTipsError", "SIM_OUT_OF_TIPS"),
    ("LocationIsOccupiedError", "SIM_DECK_CONFLICT"),
    ("is not a valid deck slot", "SIM_DECK_CONFLICT"),
    ("InvalidAspirateVolumeError", "SIM_BAD_VOLUME"),
    ("InvalidDispenseVolumeError", "SIM_BAD_VOLUME"),
    ("FileNotFoundError", "SIM_LABWARE_NOT_FOUND"),
    ("LabwareDefinitionDoesNotExist", "SIM_LABWARE_NOT_FOUND"),
]
HINTS = {
    "SIM_OUT_OF_TIPS": (
        "Use fewer wells with small additions, or ask for another tip rack.",
        False,
    ),
    "SIM_DECK_CONFLICT": ("Fix the deck layout in the workcell file.", True),
    "SIM_BAD_VOLUME": ("Change the values so every transfer fits its pipette and tip.", False),
    "SIM_LABWARE_NOT_FOUND": (
        "Fix the labware names in the workcell file or the backend map.",
        True,
    ),
    "SIM_OTHER": ("This points to a fault in the protocol generator. Keep the run folder.", True),
}

RESERVED = {"protocol", "protocol_api", "run", "metadata", "requirements"}


def prepare_environment() -> None:
    """Keep the Opentrons library's config files inside this project, not the home folder."""
    if "OT_API_CONFIG_DIR" not in os.environ:
        path = repo_root() / ".labauto" / "opentrons"
        path.mkdir(parents=True, exist_ok=True)
        os.environ["OT_API_CONFIG_DIR"] = str(path)


def _var(name: str, taken: set[str], prefix: str) -> str:
    base = name if name.isidentifier() else re.sub(r"\W", "_", name)
    if keyword.iskeyword(base) or base in RESERVED or not base.isidentifier():
        base = f"{prefix}_{base}"
    var = base
    while var in taken:
        var = f"{prefix}_{var}"
    taken.add(var)
    return var


class OpentronsOT2:
    """Backend for the Opentrons OT-2, checked in the Opentrons simulator."""

    name = "opentrons_ot2"

    def labware_map(self) -> dict[str, str]:
        return dict(LABWARE_MAP)

    def pipette_map(self) -> dict[str, str]:
        return dict(PIPETTE_MAP)

    def valid_mount(self, mount: str) -> bool:
        return mount in ("left", "right")

    def valid_position(self, position: dict) -> bool:
        slot = position.get("slot")
        return set(position) == {"slot"} and type(slot) is int and 1 <= slot <= 11

    # ------------------------------------------------------------ compile

    def render(self, worklist: Worklist, workcell: Workcell, plan: Plan) -> str:
        """The protocol source for a worklist, as readable Python."""
        taken: set[str] = set()
        lw_var = {e.name: _var(e.name, taken, "lw") for e in workcell.deck}
        pip_var = {p.name: _var(p.name, taken, "pip") for p in workcell.pipettes}

        lines = [
            f"# Generated by labauto from plan {plan.plan_id} (design {plan.design_id}). "
            "Do not edit by hand.",
            "from opentrons import protocol_api",
            "",
            f'metadata = {{"protocolName": "labauto {plan.plan_id}", "author": "labauto"}}',
            f'requirements = {{"robotType": "OT-2", "apiLevel": "{API_LEVEL}"}}',
            "",
            "",
            "def run(protocol: protocol_api.ProtocolContext):",
        ]
        for e in workcell.deck:
            load = LABWARE_MAP.get(e.labware, e.labware)
            lines.append(
                f'    {lw_var[e.name]} = protocol.load_labware("{load}", {e.position.get("slot")!r})'
            )
        for p in workcell.pipettes:
            model = PIPETTE_MAP.get(p.model, p.model)
            racks = lw_var.get(p.tips, p.tips)
            lines.append(
                f'    {pip_var[p.name]} = protocol.load_instrument("{model}", "{p.mount}", '
                f"tip_racks=[{racks}])"
            )

        rows = worklist.rows
        # A tip is dropped after the last row that uses it: the row before the
        # same pipette's next "new" row, or that pipette's final row.
        drop_after: set[int] = set()
        next_tip: dict[str, str | None] = defaultdict(lambda: None)
        for i in range(len(rows) - 1, -1, -1):
            pip = rows[i].pipette
            if next_tip[pip] in (None, "new"):
                drop_after.add(i)
            next_tip[pip] = rows[i].tip

        section = None
        for i, row in enumerate(rows):
            if not row.pipette:
                raise ValueError(f"worklist step {row.step} has no pipette that covers the volume")
            p = pip_var[row.pipette]
            bulk = row.dispense == "above_liquid"
            if (bulk, row.reagent) != section:
                section = (bulk, row.reagent)
                lines.append("")
                if bulk:
                    text = (
                        f"{row.reagent}: bulk additions, one tip, dispensed from above the liquid"
                    )
                else:
                    text = f"{row.reagent}: small additions, fresh tip per well, dispensed into the liquid"
                lines.append(f'    protocol.comment("{text}")')
            src = f'{lw_var.get(row.source_labware, row.source_labware)}["{row.source_well}"]'
            dst_well = f'{lw_var.get(row.dest_labware, row.dest_labware)}["{row.dest_well}"]'
            vol = fmt_code(row.volume_ul)
            if row.tip == "new":
                lines.append(f"    {p}.pick_up_tip()")
            lines.append(f"    {p}.aspirate({vol}, {src})")
            if bulk:
                lines.append(f"    {p}.dispense({vol}, {dst_well}.top(-2))")
                lines.append(f"    {p}.blow_out({dst_well}.top(-2))")
            else:
                lines.append(f"    {p}.dispense({vol}, {dst_well})")
            if i in drop_after:
                lines.append(f"    {p}.drop_tip()")
        if not rows:
            lines.append('    protocol.comment("nothing to transfer")')
        return "\n".join(lines) + "\n"

    def compile(self, worklist: Worklist, workcell: Workcell, plan: Plan, out_dir: Path) -> Path:
        """Write protocol.py into out_dir and return its path."""
        out_dir.mkdir(parents=True, exist_ok=True)
        path = out_dir / "protocol.py"
        path.write_text(self.render(worklist, workcell, plan), encoding="utf-8")
        return path

    # ------------------------------------------------------------ simulate

    def simulate(self, artifact: Path, workcell: Workcell) -> SimResult:
        """Run protocol.py in the Opentrons simulator, in this process."""
        return simulate_source(Path(artifact).read_text(encoding="utf-8"), workcell)


def simulate_source(source: str, workcell: Workcell | None) -> SimResult:
    """Simulate protocol source text. With a workcell, also build the ledger."""
    prepare_environment()
    notices = io.StringIO()
    start = time.perf_counter()
    try:
        with redirect_stdout(notices), redirect_stderr(notices):
            import opentrons.simulate as ot_sim

            run_log, _bundle = ot_sim.simulate(io.StringIO(source), file_name="protocol.py")
            steps = ot_sim.format_runlog(run_log).splitlines()
    except Exception as exc:  # the simulator reports every failure as an exception
        return SimResult(
            ok=False,
            instrument=OpentronsOT2.name,
            error=map_error(exc),
            seconds=round(time.perf_counter() - start, 3),
        )
    ledger, tips = read_run_log(run_log, workcell) if workcell else ([], {})
    return SimResult(
        ok=True,
        instrument=OpentronsOT2.name,
        steps=steps,
        ledger=ledger,
        tips_used=tips,
        seconds=round(time.perf_counter() - start, 3),
    )


def read_run_log(
    run_log: list[dict], workcell: Workcell
) -> tuple[list[LedgerEntry], dict[str, int]]:
    """Walk the simulator's run log and total what was dispensed into each well.

    Each pipette remembers the reagent of its last aspirate, found from the
    source well through the workcell inventory. Each dispense adds its volume
    to that reagent in the destination well.
    """
    by_slot = {str(e.position.get("slot")): e.name for e in workcell.deck}
    sources = {(inv.labware, inv.well): reagent for reagent, inv in workcell.inventory.items()}
    by_mount = {p.mount: p.name for p in workcell.pipettes}

    holding: dict[str, str] = {}
    totals: dict[tuple[str, str, str], float] = defaultdict(float)
    tips: dict[str, int] = defaultdict(int)
    for entry in run_log:
        payload = entry["payload"]
        text = payload.get("text", "")
        if not text.startswith(("Picking up tip", "Aspirating", "Dispensing")):
            continue
        instrument = payload["instrument"]
        pip = by_mount.get(instrument.mount, instrument.name)
        if text.startswith("Picking up tip"):
            tips[pip] += 1
            continue
        well = payload["location"].labware.as_well()
        deck_name = by_slot.get(str(well.parent.parent), well.parent.load_name)
        if text.startswith("Aspirating"):
            holding[pip] = sources.get(
                (deck_name, well.well_name), f"unknown:{deck_name}:{well.well_name}"
            )
        else:
            reagent = holding.get(pip, "unknown")
            totals[(deck_name, well.well_name, reagent)] += float(payload["volume"])
    ledger = [
        LedgerEntry(dest_labware=lw, dest_well=w, reagent=r, volume_ul=round(v, 6))
        for (lw, w, r), v in totals.items()
    ]
    return ledger, dict(tips)


_DETAIL = re.compile(r"detail=(?P<q>['\"])(?P<d>.*?)(?P=q), errorInfo", re.S)
_LINE = re.compile(r"\[line (\d+)\]")


def map_error(exc: BaseException) -> PlanError:
    """Turn a simulator exception into a SIM_* error, keeping the original text."""
    raw = f"{type(exc).__name__}: {exc}"
    code = "SIM_OTHER"
    for needle, mapped in ERROR_CODES:
        if needle in raw:
            code = mapped
            break
    match = _DETAIL.search(raw)
    detail = match.group("d") if match else raw.splitlines()[0][:500]
    detail = scrub_paths(detail.replace("\\'", "'"))
    line = _LINE.search(raw)
    where = f"protocol.py line {line.group(1)}" if line else "protocol.py"
    hint, needs_human = HINTS[code]
    return PlanError(
        code=code,
        layer="simulator",
        where=where,
        message=f"The Opentrons simulator stopped at {where}. Original error: {detail}",
        fix_hint=hint,
        options=["ask_human"] if needs_human else ["reduce_wells", "change_values"],
        needs_human=needs_human,
        short=where,
    )
